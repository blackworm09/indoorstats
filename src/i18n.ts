// Stage 5: DE/EN. English text is the key; German lives in DE. {name} placeholders are filled from vars.
export type Lang = 'en' | 'de';
const LANG_KEY = 'indoorstats_lang';

let lang: Lang = (() => { try { return (localStorage.getItem(LANG_KEY) as Lang) || 'en'; } catch { return 'en'; } })();
export const getLang = () => lang;
export function setLang(l: Lang) { lang = l; try { localStorage.setItem(LANG_KEY, l); } catch { /* ignore */ } }

export function t(s: string, vars?: Record<string, string | number>): string {
  let out = lang === 'de' ? (DE[s] ?? s) : s;
  if (vars) for (const k of Object.keys(vars)) out = out.split(`{${k}}`).join(String(vars[k]));
  return out;
}

